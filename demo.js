  const VOTES = [{a:3,b:2},{a:2,d:3},{b:3,c:2},{a:1,b:1,c:1,d:2},{d:4,a:1},{c:3,b:2},{a:2,b:2,d:1},{b:2,d:2,c:1},{a:3,c:2},{d:3,b:2},{a:2,c:1,d:2},{b:3,a:2},{c:2,d:3},{a:3,b:1,c:1}];
  const VOTERS = ['พญ.วรรณา (อายุรกรรม)','พว.สุดา (ผู้ป่วยนอก)','พว.ธนากร (ER)','คุณมาลี (งานเวชระเบียน)','คุณปกรณ์ (IT)','พว.อรทัย (พัฒนาคุณภาพ)','นพ.ชัยวัฒน์ (เวชกรรมสังคม)','คุณวิรัตน์ (งานช่าง)','คุณพิมพา (โภชนาการ)','กภ.นภัส (กายภาพ)','คุณสุนีย์ (การเงิน)','พทป.กาญจนา (แพทย์แผนไทย)','ภก.ศิริพงษ์ (เภสัชกรรม)','พว.นลิน (ผู้ป่วยนอก)'];

  let DB = null, uid = 0;
  const clone = x => x == null ? x : JSON.parse(JSON.stringify(x));
  const wait = ms => new Promise(r => setTimeout(r, ms));
  const now = () => new Date().toISOString();
  const nid = p => p + (++uid) + Math.random().toString(36).slice(2, 6);
  const clusterId = k => 'demo-c-' + k;

  function reset(role){
    uid = 0;
    const base = Date.now() - 1000 * 60 * 60 * 30;
    DB = {entries: [], subs: [], clusters: [], voters: {}, open: true, dots: 5, map: null, mapGone: false};
    DB.clusters = CLUSTERS.map(([k, name, note], i) => ({id: clusterId(k), name, note, sort: i, created_at: new Date(base).toISOString()}));
    ROWS.forEach(([wg, kind, body, detail, pri, cl], i) => DB.entries.push({
      id: 'demo-e' + (i + 1), wg, author: AUTHOR[wg] || 'ผู้กรอกตัวอย่าง', kind, body, detail, priority: pri,
      cluster_id: cl ? clusterId(cl) : null,
      created_at: new Date(base + i * 1000 * 60 * 17).toISOString()
    }));
    GROUPS.forEach(([wg, au], i) => {
      if (IN_PROGRESS.includes(wg)) return;
      if (wg === USER.wg && role !== 'admin') return;       // ผู้ใช้ตัวอย่างของผู้กรอก ยังไม่ส่ง ให้ลองกดส่งเอง
      DB.subs.push({wg, done: true, submitted_at: new Date(base + (i + 3) * 1000 * 60 * 61).toISOString(), submitted_by: au});
    });
    VOTERS.forEach((v, i) => { const m = {}; Object.entries(VOTES[i]).forEach(([k, n]) => m[clusterId(k)] = n); DB.voters[v] = m; });
  }
  reset('group');

  const sum = o => Object.values(o).reduce((a, b) => a + b, 0);
  const totals = () => {
    const t = {}; DB.clusters.forEach(c => t[c.id] = {total: 0, voters: 0});
    Object.values(DB.voters).forEach(m => Object.entries(m).forEach(([id, n]) => { if (t[id] && n > 0){ t[id].total += n; t[id].voters++; } }));
    return t;
  };
  const clusterStats = c => {
    const es = DB.entries.filter(e => e.cluster_id === c.id);
    return {items: es.length, groups: new Set(es.map(e => e.wg)).size};
  };

  const H = {
    sx_login: () => true,
    sx_my_entries: a => ({entries: DB.entries.filter(e => e.wg === a.p_wg), submission: DB.subs.find(s => s.wg === a.p_wg) || null}),
    sx_save_entry: a => {
      const p = a.p_entry || {}; if (!String(p.body || '').trim()) throw new Error('กรุณากรอกข้อความ');
      let e = p.id && DB.entries.find(x => x.id === p.id);
      if (e) Object.assign(e, {body: p.body, detail: p.detail || '', priority: +p.priority || 2, author: p.author || e.author});
      else { e = {id: nid('demo-n'), wg: p.wg, author: p.author, kind: p.kind, body: p.body, detail: p.detail || '', priority: +p.priority || 2, cluster_id: null, created_at: now()}; DB.entries.push(e); }
      return {id: e.id};
    },
    sx_delete_entry: a => { DB.entries = DB.entries.filter(e => !(e.id === a.p_id && e.wg === a.p_wg)); return true; },
    sx_set_done: a => {
      let s = DB.subs.find(x => x.wg === a.p_wg);
      if (!s){ s = {wg: a.p_wg}; DB.subs.push(s); }
      Object.assign(s, {done: !!a.p_done, submitted_at: now(), submitted_by: a.p_by});
      return true;
    },
    sx_peer_view: () => ({entries: DB.entries, clusters: DB.clusters, done: DB.subs.filter(s => s.done).map(s => ({wg: s.wg}))}),
    sx_vote_state: a => {
      const mine = DB.voters[a.p_voter] || {};
      return {open: DB.open, dots: DB.dots, clusters: DB.clusters.map(c => ({id: c.id, name: c.name, note: c.note, ...clusterStats(c), mine: mine[c.id] || 0}))};
    },
    sx_vote_cast: a => {
      if (!DB.open) throw new Error('ปิดรับการลงคะแนนแล้ว');
      const v = a.p_votes || {}; if (sum(v) > DB.dots) throw new Error('ใช้จุดคะแนนเกินจำนวนที่กำหนด');
      DB.voters[a.p_voter] = v; return true;
    },
    sx_admin_all: () => {
      const t = totals();
      return {
        entries: DB.entries, clusters: DB.clusters, submissions: DB.subs,
        votes: DB.clusters.map(c => ({cluster_id: c.id, total: t[c.id].total, voters: t[c.id].voters})),
        settings: {voting_open: DB.open ? '1' : '0', dots: String(DB.dots)},
        voters_total: Object.values(DB.voters).filter(m => sum(m) > 0).length
      };
    },
    sx_admin_assign: a => { (a.p_ids || []).forEach(id => { const e = DB.entries.find(x => x.id === id); if (e) e.cluster_id = a.p_cluster || null; }); return true; },
    sx_admin_save_cluster: a => {
      const p = a.p_cluster || {}; let c = p.id && DB.clusters.find(x => x.id === p.id);
      if (c){ if (p.name != null) c.name = p.name; if (p.note != null) c.note = p.note; }
      else { c = {id: nid('demo-c'), name: p.name, note: p.note || '', sort: DB.clusters.length, created_at: now()}; DB.clusters.push(c); }
      return {id: c.id};
    },
    sx_admin_delete_cluster: a => {
      DB.clusters = DB.clusters.filter(c => c.id !== a.p_id);
      DB.entries.forEach(e => { if (e.cluster_id === a.p_id) e.cluster_id = null; });
      Object.values(DB.voters).forEach(m => delete m[a.p_id]); return true;
    },
    sx_admin_set_voting: a => { DB.open = !!a.p_open; DB.dots = Math.max(1, Math.min(20, +a.p_dots || 5)); return true; },
    sx_admin_reset_votes: () => { DB.voters = {}; return true; },
    sx_map_list: () => DB.mapGone ? [] : [{id: 'demo-map', org: (DB.map || {}).org || 'โรงพยาบาลสันทราย', year: (DB.map || {}).year || '2570', updated_at: now()}],
    sx_map_get: () => {
      if (DB.map) return DB.map;
      const m = window.SMB && SMB.example ? SMB.example() : {org: 'โรงพยาบาลสันทราย', year: '2570', objectives: []};
      m.id = 'demo-map'; return m;
    },
    sx_map_save: a => { DB.map = a.p_map; DB.map.id = 'demo-map'; DB.mapGone = false; return {id: 'demo-map', updatedAt: now()}; },
    sx_map_delete: () => { DB.map = null; DB.mapGone = true; return true; }
  };

